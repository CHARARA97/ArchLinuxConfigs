local dir = vim.fn.fnamemodify(".dshtmp/install", ":p")
require('nvim-treesitter').setup({ install_dir = dir })
local t = vim.uv.hrtime()
local ok, err = pcall(function()
  require('nvim-treesitter').install({ 'doxygen' }):wait(240000)
end)
print(string.format("install ok=%s err=%s (%.1fs)", tostring(ok), tostring(err), (vim.uv.hrtime() - t) / 1e9))
print("parser exists: " .. tostring(vim.uv.fs_stat(dir .. "parser/doxygen.so") ~= nil))
print("query exists : " .. tostring(vim.uv.fs_stat(dir .. "queries/doxygen/highlights.scm") ~= nil))
vim.cmd("qa!")

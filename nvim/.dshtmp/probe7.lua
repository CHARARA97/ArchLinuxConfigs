local function dump(name)
  local id = vim.api.nvim_get_hl_id_by_name(name)
  local link = vim.api.nvim_get_hl(0, { name = name, link = true })
  local plain = vim.api.nvim_get_hl(0, { name = name, link = false })
  print(string.format("%-24s id=%-5d link=%-14s attrs=%s", name, id, tostring(link.link), vim.inspect(plain):gsub("%s+", " ")))
end
print("colorscheme = " .. tostring(vim.g.colors_name))
dump('@keyword')
dump('@keyword.doxygen')
dump('@comment.documentation')
dump('@variable.parameter')
dump('@variable.parameter.doxygen')
print("--- 显式定义 @keyword.doxygen 后 ---")
vim.api.nvim_set_hl(0, '@keyword.doxygen', { fg = '#7DCFFF', italic = true })
dump('@keyword.doxygen')
dump('@keyword')
